function normalizeCoordinatorMode(value) {
  if (value === undefined || value === null || value === '') {
    return RECORD_STORAGE_COORDINATOR_MODES.LEGACY_ONLY;
  }
  const normalized = String(value).trim().toUpperCase();
  return RECORD_STORAGE_COORDINATOR_MODES[normalized] || null;
}

